set_xmakever("2.9.8")
set_project("ros-job-forwarding-fixture")
local module_root = os.getenv("UWVM_TEST_JOB_MODULE_ROOT")
option("llvm-build-jobs")
 set_default(os.getenv("UWVM_TEST_JOB_DEFAULT"))
 after_check(function(opt)
  import("core.base.option", {alias="cli_option"})
  import("core.base.json")
  local llvm = import("utility.bundled_llvm", {rootdir=module_root, anonymous=true})
  io.writefile(os.getenv("UWVM_TEST_JOB_TRACE") .. ".check", json.encode({jobs=llvm.resolve_build_jobs(), task=cli_option.taskname and cli_option.taskname(), current_jobs=cli_option.get("jobs")}))
 end)
option_end()
target("probe")
 set_kind("phony")
 add_options("llvm-build-jobs")
 on_load(function(target)
  import("core.base.option", {alias="cli_option"})
  import("core.base.json")
  import("lib.detect.find_tool")
  local llvm = import("utility.bundled_llvm", {rootdir=module_root, anonymous=true})
  local jobs = llvm.resolve_build_jobs()
  local build = path.join(os.projectdir(), "cmake-build")
  local cmake = assert(find_tool("cmake"))
  if not os.isfile(path.join(build, "CMakeCache.txt")) then
   os.vrunv(cmake.program, {"-S", os.projectdir(), "-B", build, "-G", "Ninja"})
  end
  os.rm(path.join(build,"done"))
  llvm.build_targets(cmake.program, build, jobs, {"build.ninja"})
  llvm.build_targets(cmake.program, build, jobs, {"llvm-libraries"})
  llvm.build_targets(cmake.program, build, jobs, {"cxx_static", "cxxabi_static", "unwind_static"})
  io.writefile(os.getenv("UWVM_TEST_JOB_TRACE"), json.encode({default_jobs=os.default_njob(), jobs=jobs, task=cli_option.taskname and cli_option.taskname(), current_jobs=cli_option.get("jobs"), llvm=json.decode(io.readfile(path.join(build,"done/llvm.json"))), runtime=json.decode(io.readfile(path.join(build,"done/runtime.json")))}))
 end)
target_end()
