#!/usr/bin/env python3
"""Freeze genuine Python sources using exactly the matching build CPython.

This creates bytecode data, not a replacement implementation of Python.
Execute only in the original Linux cgroup, after the build window is released.
"""
import argparse
import hashlib
import json
import marshal
from pathlib import Path
import sys


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--cpython-source', required=True, type=Path)
    parser.add_argument('--entry', required=True, choices=['semantics', 'timed', 'profile'])
    parser.add_argument('--out', required=True, type=Path)
    args = parser.parse_args()
    if sys.version_info[:3] != (3, 14, 8) or sys.platform != 'linux':
        raise RuntimeError('must use the pinned native CPython3.14.8 on SSH Linux')
    cg = Path('/proc/self/cgroup').read_text()
    if 'docker-4dd58ad4560fde2ab9b539e4ef9cab1fac531654e99ad554aff1fce8ae0eae37.scope' not in cg:
        raise RuntimeError('not the established test cgroup')
    own = Path(__file__).resolve().parent
    args.out.mkdir(parents=True, exist_ok=False)
    modules = [
        ('encodings', args.cpython_source / 'Lib/encodings/__init__.py', True),
        ('encodings.aliases', args.cpython_source / 'Lib/encodings/aliases.py', False),
        ('encodings.utf_8', args.cpython_source / 'Lib/encodings/utf_8.py', False),
        ('encodings.ascii', args.cpython_source / 'Lib/encodings/ascii.py', False),
        ('encodings.latin_1', args.cpython_source / 'Lib/encodings/latin_1.py', False),
        ('hll_common', own / 'hll_common.py', False),
        ('hll_app', own / (args.entry + '.py'), False),
    ]
    header = ['/* Generated by pinned CPython3.14.8; do not hand edit. */']
    rows = []
    entries = []
    for index, (name, path, package) in enumerate(modules):
        source = path.read_bytes()
        virtual = f'/__uwvm_frozen__/{name.replace(".", "/")}.py'
        bytecode = marshal.dumps(compile(source, virtual, 'exec', dont_inherit=True, optimize=0))
        identifier = f'hll_code_{index}'
        header.append(f'static const unsigned char {identifier}[] = {{')
        for offset in range(0, len(bytecode), 24):
            header.append(','.join(str(v) for v in bytecode[offset:offset + 24]) + ',')
        header.append('};')
        entries.append(f'{{"{name}", {identifier}, sizeof({identifier}), {int(package)}}},')
        rows.append({'name': name, 'source': str(path.resolve()),
                     'source_sha256': hashlib.sha256(source).hexdigest(),
                     'bytecode_sha256': hashlib.sha256(bytecode).hexdigest(),
                     'bytecode_bytes': len(bytecode), 'package': package,
                     'virtual_filename': virtual})
    header.extend(['static const struct _frozen hll_frozen[] = {', *entries,
                   '{NULL, NULL, 0, 0}', '};', ''])
    (args.out / 'hll_frozen.h').write_text('\n'.join(header))
    receipt = {'version': sys.version, 'executable': sys.executable,
               'kind': 'real CPython marshal-code objects, not native Python compilation',
               'entry': args.entry, 'cgroup': cg.strip(), 'modules': rows,
               'external_runtime_assets': [], 'qualification': 'pending no-preopen native/WASI execution',
               'header_sha256': hashlib.sha256((args.out / 'hll_frozen.h').read_bytes()).hexdigest()}
    (args.out / 'frozen-assets.json').write_text(json.dumps(receipt, indent=2) + '\n')


if __name__ == '__main__':
    main()
