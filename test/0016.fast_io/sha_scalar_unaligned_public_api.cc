template <typename Hash, ::std::size_t N>
[[nodiscard]] bool digest_matches(::std::byte const* first, ::std::size_t count,
                                   ::std::array<::std::uint_least8_t, N> const& expected)
{
    // Caller supplies a count-byte subrange of the owned 258-byte input.
    // [safe: first .. first+count) ] unsafe (one-past)
    //        ^^ first             ^^ checked input end; count may be zero.
    Hash hash{};
    hash.update(first, first + count);
    hash.do_final();
    ::std::array<::std::byte, N> actual{};
    // [safe: exact N-byte owned digest destination] unsafe (one-past)
    //        ^^ actual.data(); context digest width is N by the caller type.
    hash.digest_to_byte_ptr(actual.data());
    for(::std::size_t i{}; i != N; ++i)
        if(actual[i] != static_cast<::std::byte>(expected[i])) return false;
    return true;
}

